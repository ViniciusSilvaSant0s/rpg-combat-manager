CREATE TABLE combats (
  id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES app_users(id),
  title VARCHAR2(255 CHAR) NOT NULL CHECK (TRIM(title) IS NOT NULL),
  description VARCHAR2(4000 CHAR),
  started NUMBER(1) DEFAULT 0 NOT NULL CHECK (started IN (0, 1)),
  current_participant_id NUMBER,
  version NUMBER DEFAULT 1 NOT NULL CHECK (version > 0),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX combats_user_id_ix ON combats (user_id);

CREATE TABLE combat_participants (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  combat_id NUMBER NOT NULL REFERENCES combats(id) ON DELETE CASCADE,
  combatant_id NUMBER NOT NULL REFERENCES combatants(id),
  position NUMBER NOT NULL CHECK (position >= 0),
  current_hit_points NUMBER(10) NOT NULL,
  additional_hit_points NUMBER(16) CHECK (additional_hit_points BETWEEN 0 AND 9007199254740991),
  initiative NUMBER(10),
  natural_initiative NUMBER(2) CHECK (natural_initiative IN (1, 20)),
  CONSTRAINT combat_participants_combat_id_uk UNIQUE (combat_id, id)
);
CREATE INDEX combat_participants_combat_ix ON combat_participants (combat_id);
CREATE INDEX combat_participants_combatant_ix ON combat_participants (combatant_id);

ALTER TABLE combats ADD CONSTRAINT combats_current_participant_fk
  FOREIGN KEY (id, current_participant_id) REFERENCES combat_participants (combat_id, id);

CREATE TABLE combat_participant_conditions (
  participant_id NUMBER NOT NULL REFERENCES combat_participants(id) ON DELETE CASCADE,
  condition_id VARCHAR2(64 CHAR) NOT NULL,
  CONSTRAINT combat_participant_conditions_pk PRIMARY KEY (participant_id, condition_id)
);
